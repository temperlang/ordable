"""Writes src/key-vectors.temper.md: the exact keys of a set of strings
under every combination of options, frozen, so every backend's tests
check that keys stay as they are.

    temper build -b py && uv run scripts/key_vectors.py

Keys come from the Python build (temper.out/py). Stored keys depend on
them, so run this only for a deliberate change of key format, which also
changes the format code point (`keyFormat`) and needs a new major
version.
"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "src" / "key-vectors.temper.md"
PY = ROOT / "temper.out" / "py"

# Edge cases for every level of the layout (src/key.temper.md).
STRINGS = [
    "", "a", "file2", "file10", "File2", "img12.png", "1.10", "a b-c.d",
    "x01", "x1", "x007", "1234567890", "99999999999999999999",
    "x١", "x٢١", "２０",
    "é", "É", "é", "É", "ǖ", "ǖ", "q́",
    "ß", "ẞ", "Straße", "STRASSE",
    "σ", "ς", "Σ", "K", "K", "µ", "ά",
    "Ab", "aB", "\U0001f600", "ퟻ",
]


def orders(ordable):
    """Every combination of options, in the order the test makes them."""
    casings = [ordable.Casing.ignored, ordable.Casing.last, ordable.Casing.first]
    return [ordable.Order(casing=c, upper_first=u, ignore_accents=a, ignore_number_forms=f)
            for c in casings for u in (False, True) for a in (False, True) for f in (False, True)]


def literal(s: str) -> str:
    """A Temper string literal for `s`, escaping anything but plain ASCII."""
    out = []
    for ch in s:
        if " " <= ch <= "~" and ch not in '"\\$':
            out.append(ch)
        else:
            out.append(f"\\u{{{ord(ch):X}}}")
    return '"' + "".join(out) + '"'


def hexes(key: str) -> str:
    return " ".join(f"{ord(c):x}" for c in key)


def main() -> None:
    for sub in ("ordable", "std", "temper-core"):
        sys.path.insert(0, str(PY / sub))
    sys.path.insert(0, str(PY))
    try:
        import ordable
    except ImportError as e:
        sys.exit(f"Build the Python backend first (temper build -b py): {e}")
    all_orders = orders(ordable)
    rows = []
    for s in STRINGS:
        rows.append(f"      vectors.add({literal(s)});")
        for order in all_orders:
            rows.append(f'      vectors.add("{hexes(order.key(s))}");')
    OUT.write_text(f"""# Key Vectors

Generated by `scripts/key_vectors.py`; don't edit by hand.

The exact keys of {len(STRINGS)} strings under each of the
{len(all_orders)} combinations of options, frozen, so a change to any
key fails the tests. Keys are stored, so their layout changes only on
purpose: with a new format code point (`keyFormat`), regenerated
vectors, and a new major version. Code points are in hexadecimal, as
`keyCodes` writes them.

Each string comes first, then its keys under each combination of
options, in the order `vectorOrders` makes them.

    let vectorOrders(): List<Order> {{
      let orders = new ListBuilder<Order>();
      for (let casing of [Casing.ignored, Casing.last, Casing.first]) {{
        for (let upperFirst of [false, true]) {{
          for (let ignoreAccents of [false, true]) {{
            for (let ignoreNumberForms of [false, true]) {{
              orders.add(new Order(casing, upperFirst, ignoreAccents, ignoreNumberForms));
            }}
          }}
        }}
      }}
      orders.toList()
    }}

    test("keys match the frozen vectors") {{
      let orders = vectorOrders();
      let data = keyVectors();
      let stride = orders.length + 1;
      var i = 0;
      while (i < data.length) {{
        let s = data[i];
        for (var k = 0; k < orders.length; k += 1) {{
          let key = keyCodes(orders[k].key(s));
          assert(key == data[i + 1 + k]) {{ "key of ${{s}} under options ${{k.toString()}}: ${{key}}" }}
        }}
        i += stride;
      }}
    }}

    let keyVectors(): List<String> {{
      let vectors = new ListBuilder<String>();
{chr(10).join(rows)}
      vectors.toList()
    }}
""")
    print(f"Wrote {len(STRINGS)} strings x {len(all_orders)} orders to {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
